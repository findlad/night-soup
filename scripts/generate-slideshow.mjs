import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const slideshowDirectory = path.join(root, 'public', 'slideshow');
const outputFile = path.join(root, 'app', 'slideshow-images.generated.ts');
const supportedImage = /\.(avif|gif|jpe?g|png|webp)$/i;

const customAltText = {
  'DuncanChair.jpg': 'Duncan relaxing in an oversized red chair',
  'EvanChair.jpg': 'Evan relaxing in an oversized red chair at night',
  'patioWide.jpg': 'Night Soup playing an outdoor patio show under string lights',
  'PXL_20260111_211829539.MP.jpg': 'Night Soup rehearsing together',
  'PXL_20260629_212501513.MP.jpg': 'Duncan wearing a Night Soup shirt',
};

function readableName(filename) {
  return path
    .basename(filename, path.extname(filename))
    .replace(/[_-]+/g, ' ')
    .replace(/([a-z])([A-Z])/g, '$1 $2')
    .replace(/\s+/g, ' ')
    .trim();
}

const files = (await readdir(slideshowDirectory, { withFileTypes: true }))
  .filter((entry) => entry.isFile() && supportedImage.test(entry.name))
  .map((entry) => entry.name)
  .sort((left, right) => left.localeCompare(right, undefined, { numeric: true }));

const images = files.map((filename) => ({
  src: `/slideshow/${encodeURIComponent(filename)}`,
  alt: customAltText[filename] ?? `Night Soup — ${readableName(filename)}`,
}));

const generatedFile = `// Generated by scripts/generate-slideshow.mjs. Do not edit by hand.\n\nexport const slideshowImages = ${JSON.stringify(images, null, 2)} as const;\n`;

await writeFile(outputFile, generatedFile, 'utf8');
console.log(`Found ${images.length} slideshow image${images.length === 1 ? '' : 's'}.`);
